import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(projectRoot, "src/citation-mapping/data/legacy-work-mapping.csv");
const generatedPath = resolve(
  projectRoot,
  "src/citation-mapping/generated/legacy-work-mapping.generated.ts"
);
const csvText = readFileSync(sourcePath, "utf8");
const sha256 = createHash("sha256").update(csvText, "utf8").digest("hex");
const csvStringLiteral = `'${csvText
  .replace(/\\/g, "\\\\")
  .replace(/'/g, "\\'")
  .replace(/\r/g, "\\r")
  .replace(/\n/g, "\\n")
  .replace(/\t/g, "\\t")
  .replace(/\u2028/g, "\\u2028")
  .replace(/\u2029/g, "\\u2029")}'`;
const generatedText = `// Generated by scripts/generate-citation-source-mapping.mjs.
// Do not edit this file; edit data/legacy-work-mapping.csv and regenerate it.

export const BUNDLED_LEGACY_WORK_MAPPING_CSV =
  ${csvStringLiteral};
export const BUNDLED_LEGACY_WORK_MAPPING_SHA256 =
  "${sha256}";
`;

mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(generatedPath, generatedText, "utf8");
